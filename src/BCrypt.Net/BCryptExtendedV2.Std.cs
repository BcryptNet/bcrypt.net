#if PRE_CORE
using System.Globalization;
using System.Security.Cryptography;

namespace BCryptNet;

/// <summary>
/// BCrypt Enhanced (post Bcrypt v3.5)
/// Created to be compatible with other programming-language implementations of pre-hashed keys
/// i.e. passlib in python / php bcrypt and sha
/// </summary>
///  <para>
///         To hash a password using SHA384 pre-hashing for increased entropy see <see cref="BCryptExtendedV2.HashPassword(string, int)"/>
///  </para>
///  <code>string pw_hash = BCryptExtendedV2.HashPassword(plain_password);
///        (To validate an enhanced hash use <see cref="BCryptExtendedV2.Verify(string, string, BCryptOptions)"/>)
///  </code>
[System.Diagnostics.CodeAnalysis.SuppressMessage("ApiDesign", "RS0026:Do not add multiple public overloads with optional parameters", Justification = "Overloads are for different purposes")]
public sealed class BCryptExtendedV2 : BCryptCore
{
    private const HashType DefaultEnhancedHashType = HashType.SHA384;

    /// <summary>
    ///  Pre-hash a password with SHA384 then using the OpenBSD BCrypt scheme and a salt generated by <see cref="BCryptCore.GenerateSalt(int,char)"/>.
    /// </summary>
    /// <param name="inputKey">The password to hash.</param>
    /// <param name="workFactor">The log2 of the number of rounds of hashing to apply.</param>
    /// <returns>The hashed password.</returns>
    /// <exception cref="SaltParseException">Thrown when the salt could not be parsed.</exception>
    public static string HashPassword(string inputKey, int workFactor = DefaultRounds) =>
        HashPassword(inputKey, new BCryptOptions(workFactor));

    /// <summary>
    ///  Pre-hash a password (default SHA384) then using the OpenBSD BCrypt scheme and a salt generated by <see cref="BCryptCore.GenerateSalt(int,char)"/>.
    /// </summary>
    /// <param name="inputKey">The password to hash.</param>
    /// <param name="options">Hashing options: <see cref="BCryptOptions.WorkFactor"/> sets the cost of the generated salt and <see cref="BCryptOptions.PreHash"/> selects the pre-hash algorithm (<c>null</c> uses SHA384). <see cref="HashType.None"/> is rejected; use <see cref="BCrypt"/> for plain bcrypt. <see cref="BCryptOptions.LongPasswordHandling"/> is ignored, as pre-hashed input is never subject to the 72-byte limit.</param>
    /// <returns>The hashed password.</returns>
    /// <exception cref="SaltParseException">Thrown when the salt could not be parsed.</exception>
    public static string HashPassword(string inputKey, BCryptOptions options) =>
        CreatePasswordHash(inputKey.AsSpan(), GenerateSalt(options.WorkFactor).AsSpan(), CreateContext(options));

    /// <summary>
    ///  Pre-hash a password (default SHA384) then using the OpenBSD BCrypt scheme with a manually supplied salt/>.
    /// </summary>
    /// <remarks>
    ///  <para>You should generally leave generating salts to the library.</para>
    /// </remarks>
    /// <param name="inputKey">The password to hash.</param>
    /// <param name="salt">The salt to hash with; its work factor is used and <see cref="BCryptOptions.WorkFactor"/> is ignored.</param>
    /// <param name="options">Hashing options: <see cref="BCryptOptions.PreHash"/> selects the pre-hash algorithm (<c>null</c> uses SHA384); <see cref="BCryptOptions.WorkFactor"/> is ignored as the salt carries its own. <see cref="HashType.None"/> is rejected; use <see cref="BCrypt"/> for plain bcrypt. <see cref="BCryptOptions.LongPasswordHandling"/> is ignored, as pre-hashed input is never subject to the 72-byte limit.</param>
    /// <returns>The hashed password.</returns>
    /// <exception cref="SaltParseException">Thrown when the salt could not be parsed.</exception>
    public static string HashPassword(string inputKey, string salt, BCryptOptions options = default) =>
        CreatePasswordHash(inputKey.AsSpan(), salt.AsSpan(), CreateContext(options));

    private static HashContext CreateContext(BCryptOptions options) =>
        new(options.LongPasswordHandling, ResolvePreHash(options), PreHashKind.Sha2);

    /// <summary>
    /// Context for verifying the hash being upgraded, which may be plain bcrypt (<see cref="HashType.None"/>)
    /// when migrating; the long-password policy then has to match the one it was created with.
    /// </summary>
    private static HashContext CreateCurrentHashContext(HashType currentKeyHashType, BCryptOptions options) =>
        new(options.LongPasswordHandling, currentKeyHashType, PreHashKind.Sha2);

    private static HashType ResolvePreHash(BCryptOptions options)
    {
        HashType hashType = options.ResolvePreHash(DefaultEnhancedHashType);
        if (hashType == HashType.None)
        {
            throw new ArgumentException("BCryptExtendedV2 always pre-hashes; HashType.None is not supported. Use BCrypt for plain bcrypt hashes", nameof(options));
        }

        return hashType;
    }

    /// <summary>
    /// SHA2 hashes the key and returns the base64 encoded digest (NUL terminated for revision 'a' onward) as bytes.
    /// </summary>
    /// <param name="inputKey">Input key to be hashed.</param>
    /// <param name="hashType"><seealso cref="HashType"/>HashType used</param>
    /// <param name="bcryptMinorRevision">bcrypt minor revision of the salt</param>
    /// <returns>The key material; the caller owns it and must zero it once finished.</returns>
    internal static byte[] EnhancedHash(ReadOnlySpan<char> inputKey, HashType hashType, char bcryptMinorRevision)
    {
        HashAlgorithm sha = hashType switch
        {
            HashType.SHA256 => SHA256.Create(),
            HashType.SHA384 => SHA384.Create(),
            HashType.SHA512 => SHA512.Create(),
            _ => throw new ArgumentOutOfRangeException(nameof(hashType), hashType, null)
        };

        byte[] inputBytes = null;
        byte[] digest = null;
        char[] base64Chars = null;
        try
        {
            inputBytes = EncodeUtf8(inputKey, appendNul: false);
            digest = sha.ComputeHash(inputBytes);

            base64Chars = new char[(digest.Length + 2) / 3 * 4];
            int base64Len = Convert.ToBase64CharArray(digest, 0, digest.Length, base64Chars, 0);

            // base64 is ASCII, so each char is exactly one UTF-8 byte
            bool appendNul = bcryptMinorRevision >= 'a';
            byte[] result = new byte[base64Len + (appendNul ? 1 : 0)];
            for (int i = 0; i < base64Len; i++)
            {
                result[i] = (byte)base64Chars[i];
            }

            return result;
        }
        finally
        {
            sha.Dispose();
            if (inputBytes != null) ZeroMemory(inputBytes);
            if (digest != null) ZeroMemory(digest);
            if (base64Chars != null) ZeroMemory(base64Chars);
        }
    }

    /// <summary>
    /// Compares the users stored hash with their password
    /// in a time-safe manner
    /// </summary>
    /// <param name="text"></param>
    /// <param name="hash"></param>
    /// <param name="options">Hashing options used to recompute the hash: <see cref="BCryptOptions.PreHash"/> must match the algorithm the hash was created with (<c>null</c> uses SHA384); <see cref="BCryptOptions.WorkFactor"/> is ignored as it is read from the hash. <see cref="HashType.None"/> is rejected; use <see cref="BCrypt"/> for plain bcrypt. <see cref="BCryptOptions.LongPasswordHandling"/> is ignored, as pre-hashed input is never subject to the 72-byte limit.</param>
    /// <returns></returns>
    public static bool Verify(string text, string hash, BCryptOptions options = default)
    {
        return SecureEquals(SafeUTF8.GetBytes(hash),
            SafeUTF8.GetBytes(CreatePasswordHash(text.AsSpan(), hash.AsSpan(), CreateContext(options))));
    }

    /// <summary>
    /// Validate and Upgrade Hash
    /// </summary>
    /// <remarks>The current hash is verified using the default pre-hash (SHA384).</remarks>
    /// <param name="currentKey"></param>
    /// <param name="currentHash"></param>
    /// <param name="newKey"></param>
    /// <param name="options">Hashing options for the new hash: <see cref="BCryptOptions.WorkFactor"/> sets the cost of the new hash (raised to match the current hash unless <paramref name="forceWorkFactor"/> is set), and <see cref="BCryptOptions.PreHash"/> selects the pre-hash algorithm (<c>null</c> uses SHA384). <see cref="HashType.None"/> is rejected; use <see cref="BCrypt"/> for plain bcrypt. <see cref="BCryptOptions.LongPasswordHandling"/> is ignored, as pre-hashed input is never subject to the 72-byte limit.</param>
    /// <param name="forceWorkFactor"></param>
    /// <returns></returns>
    public static string ValidateAndUpgradeHash(string currentKey,
        string currentHash,
        string newKey,
        BCryptOptions options = default,
        bool forceWorkFactor = false)
    {
        return ValidateAndUpgradeHash(currentKey, currentHash, DefaultEnhancedHashType, newKey, options, forceWorkFactor);
    }

    /// <summary>
    /// Validate and Upgrade Hash
    /// </summary>
    /// <param name="currentKey"></param>
    /// <param name="currentHash"></param>
    /// <param name="currentKeyHashType">Pre-hash algorithm the current hash was created with; use <see cref="HashType.None"/> to migrate a plain bcrypt hash.</param>
    /// <param name="newKey"></param>
    /// <param name="options">Hashing options for the new hash: <see cref="BCryptOptions.WorkFactor"/> sets the cost of the new hash (raised to match the current hash unless <paramref name="forceWorkFactor"/> is set), and <see cref="BCryptOptions.PreHash"/> selects the pre-hash algorithm (<c>null</c> uses SHA384). <see cref="HashType.None"/> is rejected; use <see cref="BCrypt"/> for plain bcrypt. <see cref="BCryptOptions.LongPasswordHandling"/> is only used to verify the current hash when <paramref name="currentKeyHashType"/> is <see cref="HashType.None"/>, and must match the policy that hash was created with.</param>
    /// <param name="forceWorkFactor"></param>
    /// <returns></returns>
    /// <exception cref="ArgumentNullException"></exception>
    /// <exception cref="ArgumentException"></exception>
    /// <exception cref="BcryptAuthenticationException"></exception>
    /// <exception cref="SaltParseException"></exception>
    public static string ValidateAndUpgradeHash(string currentKey,
        string currentHash,
        HashType currentKeyHashType,
        string newKey,
        BCryptOptions options = default,
        bool forceWorkFactor = false)
    {
        if (currentKey == null)
        {
            throw new ArgumentNullException(nameof(currentKey));
        }

        if (string.IsNullOrEmpty(currentHash) || currentHash.Length != 60)
            throw new ArgumentException("Invalid Hash", nameof(currentHash));

        // Validate the new hash's options before checking credentials
        HashContext newHashContext = CreateContext(options);

        // Throw if validation fails (password isn't valid for hash)
        string computedCurrentHash = CreatePasswordHash(currentKey.AsSpan(), currentHash.AsSpan(), CreateCurrentHashContext(currentKeyHashType, options));
        if (!SecureEquals(SafeUTF8.GetBytes(currentHash), SafeUTF8.GetBytes(computedCurrentHash)))
            throw new BcryptAuthenticationException("Current credentials could not be authenticated");

        // Throw if invalid BCrypt Version
        if (currentHash[0] != '$' || currentHash[1] != '2')
            throw new SaltParseException("Invalid bcrypt version");

        // Determine the starting offset and validate the salt
        int startingOffset = 3;

        if (currentHash[2] != '$')
        {
            char minor = currentHash[2];
            if (minor != 'a' && minor != 'b' && minor != 'x' && minor != 'y' || currentHash[3] != '$')
            {
                throw new SaltParseException("Invalid bcrypt revision");
            }

            startingOffset = 4;
        }

        // Extract number of rounds
        if (currentHash[startingOffset + 2] > '$')
        {
            throw new SaltParseException("Missing work factor");
        }

        // Extract details from salt
        int currentWorkFactor = Convert.ToInt16(currentHash.Substring(startingOffset, 2), CultureInfo.InvariantCulture);

        // Never downgrade work-factor (unless forced)
        int workFactor = options.WorkFactor;
        if (!forceWorkFactor && currentWorkFactor > workFactor)
        {
            workFactor = currentWorkFactor;
        }

        return CreatePasswordHash(newKey.AsSpan(), GenerateSalt(workFactor).AsSpan(), in newHashContext);
    }
}
#endif
