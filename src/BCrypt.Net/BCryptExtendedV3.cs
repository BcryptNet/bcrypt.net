#if NETCOREAPP
using System.Buffers;
using System.Globalization;
using System.Security.Cryptography;

namespace BCryptNet;
/// <summary>
/// BCrypt Enhanced
/// Created to be compatible with other programming-language implementations of pre-hashed keys
/// i.e. passlib in python / php bcrypt and sha
/// </summary>
///  <para>
///         To hash a password using SHA384 pre-hashing for increased entropy see <see cref="BCryptExtendedV3.HashPassword(string, string, int)"/>
///  </para>
///  <c>
///     string pw_hash = BCryptExtendedV3.HashPassword(hmac_key, plain_password);
///     // (To validate an enhanced hash use <see cref="BCryptExtendedV3.Verify(string, string, string, BCryptOptions)"/>)
///  </c>
[System.Diagnostics.CodeAnalysis.SuppressMessage("ApiDesign", "RS0026:Do not add multiple public overloads with optional parameters", Justification = "Overloads are for different purposes")]
public sealed class BCryptExtendedV3 : BCryptCore
{
    private const HashType DefaultEnhancedHashType = HashType.SHA384;

    /// <summary>
    ///  Pre-hash a password with HMAC-SHA3-384 then using the OpenBSD BCrypt scheme and a salt generated by <see cref="BCryptCore.GenerateSalt(int,char)"/>.
    /// <seealso href="https://learn.microsoft.com/en-us/dotnet/api/system.security.cryptography.hmacsha3_256?view=net-9.0"/>
    /// </summary>
    /// <param name="hmacKey">Key used in HMAC hashing</param>
    /// <param name="inputKey">The password to hash.</param>
    /// <param name="workFactor">The log2 of the number of rounds of hashing to apply.</param>
    /// <returns>The hashed password.</returns>
    /// <exception cref="SaltParseException">Thrown when the salt could not be parsed.</exception>
    public static string HashPassword(string hmacKey, string inputKey, int workFactor = DefaultRounds) =>
        HashPassword(hmacKey, inputKey, new BCryptOptions(workFactor));

    /// <summary>
    ///  Pre-hash a password with HMAC-SHA3 (default 384) then using the OpenBSD BCrypt scheme and a salt generated by <see cref="BCryptCore.GenerateSalt(int,char)"/>.
    /// <seealso href="https://learn.microsoft.com/en-us/dotnet/api/system.security.cryptography.hmacsha3_256?view=net-9.0"/>
    /// </summary>
    /// <param name="hmacKey">Key used in HMAC hashing</param>
    /// <param name="inputKey">The password to hash.</param>
    /// <param name="options">Hashing options: <see cref="BCryptOptions.WorkFactor"/> sets the cost of the generated salt and <see cref="BCryptOptions.PreHash"/> selects the pre-hash algorithm (<c>null</c> uses SHA384). <see cref="HashType.None"/> is rejected; use <see cref="BCrypt"/> for plain bcrypt. <see cref="BCryptOptions.LongPasswordHandling"/> is ignored, as pre-hashed input is never subject to the 72-byte limit.</param>
    /// <returns>The hashed password.</returns>
    /// <exception cref="SaltParseException">Thrown when the salt could not be parsed.</exception>
    public static string HashPassword(string hmacKey, string inputKey, BCryptOptions options)
    {
        ArgumentNullException.ThrowIfNull(hmacKey);
        return CreatePasswordHash(inputKey, GenerateSalt(options.WorkFactor), CreateContext(hmacKey, options));
    }

    /// <summary>
    ///  Pre-hash a password with HMAC-SHA3 (default 384) then using the OpenBSD BCrypt scheme with a manually supplied salt.
    /// <seealso href="https://learn.microsoft.com/en-us/dotnet/api/system.security.cryptography.hmacsha3_256?view=net-9.0"/>
    /// </summary>
    /// <remarks>
    ///  <para>You should generally leave generating salts to the library.</para>
    /// </remarks>
    /// <param name="hmacKey">Key used in HMAC hashing</param>
    /// <param name="inputKey">The password to hash.</param>
    /// <param name="salt">The salt to hash with; its work factor is used and <see cref="BCryptOptions.WorkFactor"/> is ignored.</param>
    /// <param name="options">Hashing options: <see cref="BCryptOptions.PreHash"/> selects the pre-hash algorithm (<c>null</c> uses SHA384); <see cref="BCryptOptions.WorkFactor"/> is ignored as the salt carries its own. <see cref="HashType.None"/> is rejected; use <see cref="BCrypt"/> for plain bcrypt. <see cref="BCryptOptions.LongPasswordHandling"/> is ignored, as pre-hashed input is never subject to the 72-byte limit.</param>
    /// <returns>The hashed password.</returns>
    /// <exception cref="SaltParseException">Thrown when the salt could not be parsed.</exception>
    public static string HashPassword(string hmacKey, string inputKey, string salt, BCryptOptions options = default) =>
        HashPassword(hmacKey, inputKey.AsSpan(), salt.AsSpan(), options);

    /// <inheritdoc cref="HashPassword(string, string, string, BCryptOptions)"/>
    public static string HashPassword(string hmacKey, ReadOnlySpan<char> inputKey, ReadOnlySpan<char> salt, BCryptOptions options = default)
    {
        ArgumentNullException.ThrowIfNull(hmacKey);
        return CreatePasswordHash(inputKey, salt, CreateContext(hmacKey, options));
    }

    private static HashContext CreateContext(ReadOnlySpan<char> hmacKey, BCryptOptions options) =>
        new(options.LongPasswordHandling, ResolvePreHash(options), PreHashKind.HmacSha3, hmacKey);

    /// <summary>
    /// Context for verifying the hash being upgraded, which may be plain bcrypt (<see cref="HashType.None"/>)
    /// when migrating; the long-password policy then has to match the one it was created with.
    /// </summary>
    private static HashContext CreateCurrentHashContext(ReadOnlySpan<char> hmacKey, HashType currentKeyHashType, BCryptOptions options) =>
        new(options.LongPasswordHandling, currentKeyHashType, PreHashKind.HmacSha3, hmacKey);

    // HashType.None would skip the HMAC entirely, silently dropping the key
    private static HashType ResolvePreHash(BCryptOptions options)
    {
        HashType hashType = options.ResolvePreHash(DefaultEnhancedHashType);
        if (hashType == HashType.None)
        {
            throw new ArgumentException("BCryptExtendedV3 always pre-hashes; HashType.None would ignore the HMAC key. Use BCrypt for plain bcrypt hashes", nameof(options));
        }

        return hashType;
    }

    /// <summary>
    /// HMAC-SHA3 hashes an input key before bcrypt hashing
    /// </summary>
    /// <param name="hmacKey">Key used in HMAC hashing</param>
    /// <param name="inputKey">Input key to be hashed.</param>
    /// <param name="hashType"><seealso cref="HashType"/>HashType used (default SHA3 HMAC 384 - https://learn.microsoft.com/en-us/dotnet/api/system.security.cryptography.hmacsha3_256)</param>
    /// <param name="destination">Destination buffer for the hashed output.</param>
    /// <param name="bcryptMinorRevision">(Default: 'a')</param>
    /// <returns>Number of bytes written to <paramref name="destination"/>.</returns>
    internal static int EnhancedHash(ReadOnlySpan<char> hmacKey, ReadOnlySpan<char> inputKey, HashType hashType, Span<byte> destination, char bcryptMinorRevision = 'a')
    {
        ushort hashLen = hashType switch
        {
            HashType.SHA256 => 32,
            HashType.SHA384 => 48,
            HashType.SHA512 => 64,
            _ => throw new ArgumentOutOfRangeException(nameof(hashType))
        };

        int keyMaxBytes = SafeUTF8.GetMaxByteCount(hmacKey.Length);
        int dataMaxBytes = SafeUTF8.GetMaxByteCount(inputKey.Length);
        byte[] keyRented = keyMaxBytes <= StackallocByteThreshold ? null : ArrayPool<byte>.Shared.Rent(keyMaxBytes);
        byte[] dataRented = dataMaxBytes <= StackallocByteThreshold ? null : ArrayPool<byte>.Shared.Rent(dataMaxBytes);
        Span<byte> keyBytes = keyRented ?? stackalloc byte[StackallocByteThreshold];
        Span<byte> dataBytes = dataRented ?? stackalloc byte[StackallocByteThreshold];
        Span<byte> hash = stackalloc byte[hashLen];

        try
        {
            // UTF8 encode key and data
            int keyByteLen = SafeUTF8.GetBytes(hmacKey, keyBytes);
            int dataByteLen = SafeUTF8.GetBytes(inputKey, dataBytes);

            // Perform HMAC
            bool success = hashType switch
            {
                HashType.SHA256 => HMACSHA3_256.TryHashData(keyBytes[..keyByteLen], dataBytes[..dataByteLen], hash, out int len) && len == 32,
                HashType.SHA384 => HMACSHA3_384.TryHashData(keyBytes[..keyByteLen], dataBytes[..dataByteLen], hash, out int len) && len == 48,
                HashType.SHA512 => HMACSHA3_512.TryHashData(keyBytes[..keyByteLen], dataBytes[..dataByteLen], hash, out int len) && len == 64,
                _ => throw new ArgumentOutOfRangeException(nameof(hashType))
            };

            if (!success)
                throw new BcryptAuthenticationException($"HMAC-{hashType} failed");

            // Base64 encode, appending `Nul` only **after** base64 encoding
            return EncodePreHash(hash, bcryptMinorRevision, destination);
        }
        finally
        {
            ZeroMemory(keyBytes);
            ZeroMemory(dataBytes);
            ZeroMemory(hash);
            if (keyRented != null)
            {
                ArrayPool<byte>.Shared.Return(keyRented);
            }

            if (dataRented != null)
            {
                ArrayPool<byte>.Shared.Return(dataRented);
            }
        }
    }

    /// <summary>
    /// Compares the users stored hash with their password
    /// in a time-safe manner
    /// </summary>
    /// <param name="hmacKey">Key used in HMAC hashing</param>
    /// <param name="inputKey"></param>
    /// <param name="hash"></param>
    /// <param name="options">Hashing options used to recompute the hash: <see cref="BCryptOptions.PreHash"/> must match the algorithm the hash was created with (<c>null</c> uses SHA384); <see cref="BCryptOptions.WorkFactor"/> is ignored as it is read from the hash. <see cref="HashType.None"/> is rejected; use <see cref="BCrypt"/> for plain bcrypt. <see cref="BCryptOptions.LongPasswordHandling"/> is ignored, as pre-hashed input is never subject to the 72-byte limit.</param>
    /// <returns></returns>
    public static bool Verify(string hmacKey, string inputKey, string hash, BCryptOptions options = default)
    {
        ArgumentNullException.ThrowIfNull(hmacKey);
        return VerifyHash(inputKey, hash, CreateContext(hmacKey, options));
    }

    /// <summary>
    /// Validate and Upgrade Hash
    /// </summary>
    /// <param name="hmacKey">Key used in HMAC hashing</param>
    /// <param name="currentKey"></param>
    /// <param name="currentHash"></param>
    /// <param name="currentKeyHashType">Pre-hash algorithm the current hash was created with; use <see cref="HashType.None"/> to migrate a plain bcrypt hash.</param>
    /// <param name="newKey"></param>
    /// <param name="options">Hashing options for the new hash: <see cref="BCryptOptions.WorkFactor"/> sets the cost of the new hash (raised to match the current hash unless <paramref name="forceWorkFactor"/> is set), and <see cref="BCryptOptions.PreHash"/> selects the pre-hash algorithm (<c>null</c> uses SHA384). <see cref="HashType.None"/> is rejected; use <see cref="BCrypt"/> for plain bcrypt. <see cref="BCryptOptions.LongPasswordHandling"/> is only used to verify the current hash when <paramref name="currentKeyHashType"/> is <see cref="HashType.None"/>, and must match the policy that hash was created with.</param>
    /// <param name="forceWorkFactor"></param>
    /// <returns></returns>
    /// <exception cref="ArgumentNullException"></exception>
    /// <exception cref="ArgumentException"></exception>
    /// <exception cref="BcryptAuthenticationException"></exception>
    /// <exception cref="SaltParseException"></exception>
    public static string ValidateAndUpgradeHash(
        string hmacKey,
        string currentKey,
        string currentHash,
        HashType currentKeyHashType,
        string newKey,
        BCryptOptions options = default,
        bool forceWorkFactor = false)
    {
        ArgumentNullException.ThrowIfNull(hmacKey);
        ArgumentNullException.ThrowIfNull(currentKey);

        if (string.IsNullOrEmpty(currentHash) || currentHash.Length != 60)
            throw new ArgumentException("Invalid Hash", nameof(currentHash));

        // Validate the new hash's options before checking credentials
        HashContext newHashContext = CreateContext(hmacKey, options);

        // Throw if validation fails (password isn't valid for hash)
        if (!VerifyHash(currentKey, currentHash, CreateCurrentHashContext(hmacKey, currentKeyHashType, options)))
            throw new BcryptAuthenticationException("Current credentials could not be authenticated");

        // Throw if invalid BCrypt Version
        if (currentHash[0] != '$' || currentHash[1] != '2')
            throw new SaltParseException("Invalid bcrypt version");

        // Determine the starting offset and validate the salt
        int startingOffset = 3;

        if (currentHash[2] != '$')
        {
            char minor = currentHash[2];
            if (minor != 'a' && minor != 'b' && minor != 'x' && minor != 'y' || currentHash[3] != '$')
            {
                throw new SaltParseException("Invalid bcrypt revision");
            }

            startingOffset = 4;
        }

        // Extract number of rounds
        if (currentHash[startingOffset + 2] > '$')
        {
            throw new SaltParseException("Missing work factor");
        }

        // Extract details from salt
        int currentWorkFactor = int.Parse(currentHash.AsSpan(startingOffset, 2), NumberStyles.None, CultureInfo.InvariantCulture);

        // Never downgrade work-factor (unless forced)
        int workFactor = options.WorkFactor;
        if (!forceWorkFactor && currentWorkFactor > workFactor)
        {
            workFactor = currentWorkFactor;
        }

        return CreatePasswordHash(newKey, GenerateSalt(workFactor), in newHashContext);
    }
}
#endif
