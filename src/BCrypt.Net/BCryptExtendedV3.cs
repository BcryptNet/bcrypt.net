#if NETCOREAPP
using System.Buffers;
using System.Security.Cryptography;

namespace BCryptNet;
/// <summary>
/// BCrypt Enhanced
/// Created to be compatible with other programming-language implementations of pre-hashed keys
/// i.e. passlib in python / php bcrypt and sha
/// </summary>
///  <para>
///         To hash a password using SHA384 pre-hashing for increased entropy see <see cref="BCryptExtendedV3.HashPassword(HmacKey, string, int)"/>
///  </para>
///  <c>
///     using HmacKey hmac_key = HmacKey.FromString(pepper);
///     string pw_hash = BCryptExtendedV3.HashPassword(hmac_key, plain_password);
///     // (To validate an enhanced hash use <see cref="BCryptExtendedV3.Verify(HmacKey, string, string, BCryptOptions)"/>)
///  </c>
[System.Diagnostics.CodeAnalysis.SuppressMessage("ApiDesign", "RS0026:Do not add multiple public overloads with optional parameters", Justification = "Overloads are for different purposes")]
public sealed class BCryptExtendedV3 : BCryptCore
{
    /// <summary>
    ///  Pre-hash a password with HMAC-SHA3-384 then using the OpenBSD BCrypt scheme and a salt generated by <see cref="BCryptCore.GenerateSalt(int,char)"/>.
    /// <seealso href="https://learn.microsoft.com/en-us/dotnet/api/system.security.cryptography.hmacsha3_256?view=net-9.0"/>
    /// </summary>
    /// <param name="hmacKey">Key used in HMAC hashing (the "pepper")</param>
    /// <param name="inputKey">The password to hash.</param>
    /// <param name="workFactor">The log2 of the number of rounds of hashing to apply.</param>
    /// <returns>The hashed password.</returns>
    /// <exception cref="SaltParseException">Thrown when the salt could not be parsed.</exception>
    public static string HashPassword(HmacKey hmacKey, string inputKey, int workFactor = DefaultRounds) =>
        HashPassword(hmacKey, inputKey, new BCryptOptions(workFactor));

    /// <summary>
    ///  Pre-hash a password with HMAC-SHA3 (default 384) then using the OpenBSD BCrypt scheme and a salt generated by <see cref="BCryptCore.GenerateSalt(int,char)"/>.
    /// <seealso href="https://learn.microsoft.com/en-us/dotnet/api/system.security.cryptography.hmacsha3_256?view=net-9.0"/>
    /// </summary>
    /// <param name="hmacKey">Key used in HMAC hashing (the "pepper")</param>
    /// <param name="inputKey">The password to hash.</param>
    /// <param name="options">Hashing options: <see cref="BCryptOptions.WorkFactor"/> sets the cost of the generated salt and <see cref="BCryptOptions.PreHash"/> selects the pre-hash algorithm (<c>null</c> uses <see cref="PreHash.HmacSha3"/> SHA384). Only <see cref="PreHashScheme.HmacSha3"/> is accepted; use <see cref="BCrypt"/> for plain bcrypt. <see cref="BCryptOptions.LongPasswordHandling"/> is ignored, as pre-hashed input is never subject to the 72-byte limit.</param>
    /// <returns>The hashed password.</returns>
    /// <exception cref="SaltParseException">Thrown when the salt could not be parsed.</exception>
    public static string HashPassword(HmacKey hmacKey, string inputKey, BCryptOptions options) =>
        CreatePasswordHash(inputKey, GenerateSalt(options.WorkFactor), CreateContext(hmacKey, options));

    /// <summary>
    ///  Pre-hash a password with HMAC-SHA3 (default 384) then using the OpenBSD BCrypt scheme with a manually supplied salt.
    /// <seealso href="https://learn.microsoft.com/en-us/dotnet/api/system.security.cryptography.hmacsha3_256?view=net-9.0"/>
    /// </summary>
    /// <remarks>
    ///  <para>You should generally leave generating salts to the library.</para>
    /// </remarks>
    /// <param name="hmacKey">Key used in HMAC hashing (the "pepper")</param>
    /// <param name="inputKey">The password to hash.</param>
    /// <param name="salt">The salt to hash with; its work factor is used and <see cref="BCryptOptions.WorkFactor"/> is ignored.</param>
    /// <param name="options">Hashing options: <see cref="BCryptOptions.PreHash"/> selects the pre-hash algorithm (<c>null</c> uses <see cref="PreHash.HmacSha3"/> SHA384); <see cref="BCryptOptions.WorkFactor"/> is ignored as the salt carries its own. Only <see cref="PreHashScheme.HmacSha3"/> is accepted; use <see cref="BCrypt"/> for plain bcrypt. <see cref="BCryptOptions.LongPasswordHandling"/> is ignored, as pre-hashed input is never subject to the 72-byte limit.</param>
    /// <returns>The hashed password.</returns>
    /// <exception cref="SaltParseException">Thrown when the salt could not be parsed.</exception>
    public static string HashPassword(HmacKey hmacKey, string inputKey, string salt, BCryptOptions options = default) =>
        HashPassword(hmacKey, inputKey.AsSpan(), salt.AsSpan(), options);

    /// <inheritdoc cref="HashPassword(HmacKey, string, string, BCryptOptions)"/>
    public static string HashPassword(HmacKey hmacKey, ReadOnlySpan<char> inputKey, ReadOnlySpan<char> salt, BCryptOptions options = default) =>
        CreatePasswordHash(inputKey, salt, CreateContext(hmacKey, options));

    private static HashContext CreateContext(HmacKey hmacKey, BCryptOptions options) =>
        HashContext.Create(ResolvePreHash(options), options.LongPasswordHandling, hmacKey, nameof(hmacKey));

    /// <summary>
    /// Context for verifying the hash being upgraded, which may be plain bcrypt (<see cref="HashType.None"/>)
    /// when migrating; the long-password policy then has to match the one it was created with.
    /// </summary>
    private static HashContext CreateCurrentHashContext(HmacKey hmacKey, HashType currentKeyHashType, BCryptOptions options) =>
        currentKeyHashType == HashType.None
            ? HashContext.Create(PreHash.None, options.LongPasswordHandling, null, nameof(hmacKey))
            : HashContext.Create(PreHash.HmacSha3(currentKeyHashType), options.LongPasswordHandling, hmacKey, nameof(hmacKey));

    // Any other scheme would skip the HMAC entirely, silently dropping the key
    private static PreHash ResolvePreHash(BCryptOptions options)
    {
        PreHash preHash = options.ResolvePreHash(PreHash.HmacSha3());
        if (preHash.Scheme != PreHashScheme.HmacSha3)
        {
            throw new ArgumentException($"BCryptExtendedV3 only supports {nameof(PreHashScheme.HmacSha3)} pre-hashing, not {preHash}, as anything else would ignore the HMAC key. Use BCrypt for plain bcrypt hashes, or BCrypt.ValidateAndUpgradeHash to change scheme", nameof(options));
        }

        return preHash;
    }

    /// <summary>
    /// HMAC-SHA3 hashes an input key before bcrypt hashing
    /// </summary>
    /// <param name="hmacKey">Key used in HMAC hashing, already encoded (see <see cref="HmacKey"/>)</param>
    /// <param name="inputKey">Input key to be hashed.</param>
    /// <param name="hashType"><seealso cref="HashType"/>HashType used (default SHA3 HMAC 384 - https://learn.microsoft.com/en-us/dotnet/api/system.security.cryptography.hmacsha3_256)</param>
    /// <param name="destination">Destination buffer for the hashed output.</param>
    /// <param name="bcryptMinorRevision">(Default: 'a')</param>
    /// <returns>Number of bytes written to <paramref name="destination"/>.</returns>
    internal static int EnhancedHash(ReadOnlySpan<byte> hmacKey, ReadOnlySpan<char> inputKey, HashType hashType, Span<byte> destination, char bcryptMinorRevision = 'a')
    {
        ushort hashLen = hashType switch
        {
            HashType.SHA256 => 32,
            HashType.SHA384 => 48,
            HashType.SHA512 => 64,
            _ => throw new ArgumentOutOfRangeException(nameof(hashType))
        };

        int dataMaxBytes = SafeUTF8.GetMaxByteCount(inputKey.Length);
        byte[] dataRented = dataMaxBytes <= StackallocByteThreshold ? null : ArrayPool<byte>.Shared.Rent(dataMaxBytes);
        Span<byte> dataBytes = dataRented ?? stackalloc byte[StackallocByteThreshold];
        Span<byte> hash = stackalloc byte[hashLen];

        try
        {
            // UTF8 encode data; the key is encoded once when the HmacKey is created
            int dataByteLen = SafeUTF8.GetBytes(inputKey, dataBytes);

            // Perform HMAC
            bool success = hashType switch
            {
                HashType.SHA256 => HMACSHA3_256.TryHashData(hmacKey, dataBytes[..dataByteLen], hash, out int len) && len == 32,
                HashType.SHA384 => HMACSHA3_384.TryHashData(hmacKey, dataBytes[..dataByteLen], hash, out int len) && len == 48,
                HashType.SHA512 => HMACSHA3_512.TryHashData(hmacKey, dataBytes[..dataByteLen], hash, out int len) && len == 64,
                _ => throw new ArgumentOutOfRangeException(nameof(hashType))
            };

            if (!success)
                throw new BcryptAuthenticationException($"HMAC-{hashType} failed");

            // Base64 encode, appending `Nul` only **after** base64 encoding
            return EncodePreHash(hash, bcryptMinorRevision, destination);
        }
        finally
        {
            ZeroMemory(dataBytes);
            ZeroMemory(hash);
            if (dataRented != null)
            {
                ArrayPool<byte>.Shared.Return(dataRented);
            }
        }
    }

    /// <summary>
    /// Compares the users stored hash with their password
    /// in a time-safe manner
    /// </summary>
    /// <param name="hmacKey">Key used in HMAC hashing (the "pepper")</param>
    /// <param name="inputKey"></param>
    /// <param name="hash"></param>
    /// <param name="options">Hashing options used to recompute the hash: <see cref="BCryptOptions.PreHash"/> must match the algorithm the hash was created with (<c>null</c> uses <see cref="PreHash.HmacSha3"/> SHA384); <see cref="BCryptOptions.WorkFactor"/> is ignored as it is read from the hash. Only <see cref="PreHashScheme.HmacSha3"/> is accepted; use <see cref="BCrypt"/> for plain bcrypt. <see cref="BCryptOptions.LongPasswordHandling"/> is ignored, as pre-hashed input is never subject to the 72-byte limit.</param>
    /// <returns></returns>
    public static bool Verify(HmacKey hmacKey, string inputKey, string hash, BCryptOptions options = default) =>
        VerifyHash(inputKey, hash, CreateContext(hmacKey, options));

    /// <summary>
    /// Validate and Upgrade Hash
    /// </summary>
    /// <param name="hmacKey">Key used in HMAC hashing (the "pepper")</param>
    /// <param name="currentKey"></param>
    /// <param name="currentHash"></param>
    /// <param name="currentKeyHashType">Pre-hash algorithm the current hash was created with; use <see cref="HashType.None"/> to migrate a plain bcrypt hash.</param>
    /// <param name="newKey"></param>
    /// <param name="options">Hashing options for the new hash: <see cref="BCryptOptions.WorkFactor"/> sets the cost of the new hash (raised to match the current hash unless <paramref name="forceWorkFactor"/> is set), and <see cref="BCryptOptions.PreHash"/> selects the pre-hash algorithm (<c>null</c> uses <see cref="PreHash.HmacSha3"/> SHA384). Only <see cref="PreHashScheme.HmacSha3"/> is accepted; use <see cref="BCrypt"/> for plain bcrypt. <see cref="BCryptOptions.LongPasswordHandling"/> is only used to verify the current hash when <paramref name="currentKeyHashType"/> is <see cref="HashType.None"/>, and must match the policy that hash was created with.</param>
    /// <param name="forceWorkFactor"></param>
    /// <returns></returns>
    /// <exception cref="ArgumentNullException"></exception>
    /// <exception cref="ArgumentException"></exception>
    /// <exception cref="BcryptAuthenticationException"></exception>
    /// <exception cref="SaltParseException"></exception>
    public static string ValidateAndUpgradeHash(
        HmacKey hmacKey,
        string currentKey,
        string currentHash,
        HashType currentKeyHashType,
        string newKey,
        BCryptOptions options = default,
        bool forceWorkFactor = false)
    {
        // Validate the new hash's options before checking credentials
        HashContext newContext = CreateContext(hmacKey, options);
        HashContext currentContext = CreateCurrentHashContext(hmacKey, currentKeyHashType, options);
        return UpgradeHash(currentKey, currentHash, in currentContext, newKey, in newContext, options.WorkFactor, forceWorkFactor);
    }
}
#endif
